"use server";

import { revalidatePath } from "next/cache";
import { requireUser } from "@/lib/auth/session";
import { friendlyError } from "@/lib/errors";
import { downloadName } from "@/lib/pdf/model";
import {
  outcomeText,
  processBookingPdf,
  type PipelineClient,
} from "@/lib/pdf/pipeline";
import { renderBookingPdf } from "@/lib/pdf/render";
import { createClient } from "@/lib/supabase/server";
import { SIGNED_URL_SECONDS, isUuid } from "@/lib/storage/files";

/**
 * Booking PDF actions. Every one starts with requireUser() and works with THE USER'S OWN LOGIN, so row-level security
 * and the database functions' own checks apply. No storage path ever comes from the browser: a download is asked for by
 * a version id, the path is read from the database, and the link works for 60 seconds.
 */
export type PdfActionResult =
  | { ok: true; message: string; created: boolean }
  | { ok: false; message: string };

/** The "Regenerate PDF" button. Nothing printed changed since the latest version = no new version (FR-PDF-5). */
export async function regeneratePdfAction(
  bookingId: string,
): Promise<PdfActionResult> {
  await requireUser();
  if (!isUuid(bookingId))
    return { ok: false, message: "That booking was not found." };
  const supabase = await createClient();
  const q = await supabase.rpc("request_pdf_regeneration", {
    p_booking: bookingId,
  });
  if (q.error) return { ok: false, message: friendlyError(q.error) };
  const out = await processBookingPdf(
    supabase as unknown as PipelineClient,
    bookingId,
    { render: renderBookingPdf, reason: "regenerated by a person" },
  );
  revalidatePath(`/bookings/${bookingId}`);
  return out.status === "failed"
    ? { ok: false, message: outcomeText(out) }
    : {
        ok: true,
        message: outcomeText(out),
        created: out.status === "created",
      };
}

export type PdfUrlResult =
  | { ok: true; url: string; expiresInSeconds: number }
  | { ok: false; message: string };

/** A 60-second download link for one saved version, named like "AAA-2026-000001-v2.pdf". */
export async function pdfDownloadAction(
  versionId: string,
): Promise<PdfUrlResult> {
  await requireUser();
  if (!isUuid(versionId))
    return { ok: false, message: "That file was not found." };
  const supabase = await createClient();
  const { data: v } = await supabase
    .from("booking_pdf_versions")
    .select("storage_path, version_no, booking_id")
    .eq("id", versionId)
    .maybeSingle();
  if (!v) return { ok: false, message: "That file was not found." };
  const { data: b } = await supabase
    .from("bookings")
    .select("booking_code")
    .eq("id", v.booking_id)
    .maybeSingle();
  const { data, error } = await supabase.storage
    .from("booking-pdfs")
    .createSignedUrl(v.storage_path, SIGNED_URL_SECONDS, {
      download: downloadName(b?.booking_code ?? "booking", v.version_no),
    });
  if (error || !data)
    return {
      ok: false,
      message: "We could not open that file. Please try again.",
    };
  return {
    ok: true,
    url: data.signedUrl,
    expiresInSeconds: SIGNED_URL_SECONDS,
  };
}
